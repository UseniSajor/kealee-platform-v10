  /**
   * Insert MEP system blocks and entities.
   */
  private static generateMEPInserts(mepReport: MEPReport): string[] {
    const lines: string[] = [];

    // Insert electrical fixtures
    for (const fixture of mepReport.electrical_fixtures) {
      lines.push('INSERT');
      lines.push('8');
      lines.push('E-ELEC');
      lines.push('2');
      lines.push(fixture.type === 'outlet-duplex' || fixture.type === 'outlet-gfci' ? 'OUTLET' : 'SWITCH');
      lines.push('10');
      lines.push(fixture.location.x.toFixed(3));
      lines.push('20');
      lines.push(fixture.location.y.toFixed(3));
      lines.push('30');
      lines.push('0.0');
      lines.push('41');
      lines.push('1.0');
      lines.push('42');
      lines.push('1.0');
      lines.push('43');
      lines.push('1.0');
      lines.push('50');
      lines.push('0');
    }

    // HVAC ducts as polylines
    for (const duct of mepReport.hvac_ducts) {
      lines.push('LWPOLYLINE');
      lines.push('8');
      lines.push(duct.supply ? 'M-HVAC' : 'M-HVAC');
      lines.push('70');
      lines.push('0');
      lines.push('90');
      lines.push(duct.centerline.length.toString());

      for (const pt of duct.centerline) {
        lines.push('10');
        lines.push(pt.x.toFixed(3));
        lines.push('20');
        lines.push(pt.y.toFixed(3));
      }

      lines.push('43');
      lines.push((duct.diameter / 12).toFixed(2)); // Width
    }

    // Plumbing fixtures as circles
    for (const fixture of mepReport.plumbing_fixtures) {
      lines.push('CIRCLE');
      lines.push('8');
      lines.push('P-PLUM');
      lines.push('62');
      lines.push('6'); // Magenta
      lines.push('10');
      lines.push(fixture.location.x.toFixed(3));
      lines.push('20');
      lines.push(fixture.location.y.toFixed(3));
      lines.push('40');
      lines.push('0.25');
    }

    return lines;
  }

