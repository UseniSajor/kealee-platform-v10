  /**
   * Generate 3D wall entities with faces.
   */
  private static generateWall3D(wall: Wall3D): string[] {
    const lines: string[] = [];

    // Draw wall as 3D polyface mesh
    for (const face of wall.faces) {
      lines.push('3DFACE');
      lines.push('8');
      lines.push(wall.external ? 'A-WALL-EXTR' : 'A-WALL');
      lines.push('62');
      lines.push('1'); // Red
      lines.push('70');
      lines.push('0');

      for (let i = 0; i < Math.min(4, face.vertices.length); i++) {
        const v = face.vertices[i];
        const groupCode = 10 + i;
        const yGroupCode = 20 + i;
        const zGroupCode = 30 + i;
        lines.push(groupCode.toString());
        lines.push(v.x.toFixed(3));
        lines.push(yGroupCode.toString());
        lines.push(v.y.toFixed(3));
        lines.push(zGroupCode.toString());
        lines.push(v.z.toFixed(3));
      }
    }

    return lines;
  }

  /**
   * Generate slab entities.
   */
  private static generateSlab(slab: Slab3D): string[] {
    const lines: string[] = ['LWPOLYLINE', '8', 'A-FLOR-SLAB', '70', '1', '90', slab.points.length.toString()];

    for (const pt of slab.points) {
      lines.push('10');
      lines.push(pt.x.toFixed(3));
      lines.push('20');
      lines.push(pt.y.toFixed(3));
    }

    return lines;
  }

